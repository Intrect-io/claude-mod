#!/usr/bin/env bun
// Created: 2026-10-29
// Purpose: Write the files that several mods share from shared/. A mod imports
//   nothing outside its folder, so each one keeps its own copy. This script is
//   the only thing that writes those copies, and --check fails (exit 1) when
//   any copy differs from what it would write.
// Dependencies: bun
// Test Status: run by scripts/ci.sh (--check) on every pull request
//
// Usage: bun scripts/sync-shared.ts [--check]

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(import.meta.path), '..')

type Copy = { source: string; target: string; vars?: Record<string, string> }

const COPIES: Copy[] = [
  ...['goal-mode', 'harness', 'model-tier', 'auto-claude'].map(mod => ({
    source: 'shared/segment.ts',
    target: `${mod}/hooks/segment.ts`,
    vars: { MOD: mod },
  })),
  ...['goal-mode', 'auto-claude'].map(mod => ({ source: 'shared/queue.ts', target: `${mod}/hooks/queue.ts` })),
]

export function render(copy: Copy, text: string): string {
  let body = text
  for (const [name, value] of Object.entries(copy.vars ?? {})) body = body.replaceAll(`{{${name}}}`, value)
  const left = body.match(/\{\{[A-Z_]+\}\}/)
  if (left !== null) throw new Error(`${copy.source}: ${left[0]} has no value for ${copy.target}`)

  return `// Generated by scripts/sync-shared.ts from ${copy.source}. Edit that file, then run: bun scripts/sync-shared.ts\n${body}`
}

const check = process.argv.includes('--check')
const drifted: string[] = []
for (const copy of COPIES) {
  const want = render(copy, readFileSync(join(ROOT, copy.source), 'utf8'))
  let have: string | undefined
  try {
    have = readFileSync(join(ROOT, copy.target), 'utf8')
  } catch {
    have = undefined
  }
  if (have === want) continue
  if (check) drifted.push(copy.target)
  else {
    writeFileSync(join(ROOT, copy.target), want)
    console.log(`wrote ${copy.target}`)
  }
}

if (drifted.length > 0) {
  console.error(`sync-shared: these copies differ from shared/ (run bun scripts/sync-shared.ts):\n  ${drifted.join('\n  ')}`)
  process.exit(1)
}
if (check) console.log(`sync-shared: ${COPIES.length} copies match shared/`)
